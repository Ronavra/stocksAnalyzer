-- Prediction ledger. Applied to the hosted Supabase project on 2026-09-21.
create table if not exists public.research_predictions (
 id bigint generated by default as identity primary key,
 company_id bigint not null references public.companies(id) on delete cascade,
 signal_date date not null,
 horizon_days integer not null default 5 check (horizon_days in (5,10,20)),
 signal text not null check (signal in ('UP','NO_SIGNAL')),
 rank integer,
 entry_price numeric,
 research_score numeric,
 historical_up_rate numeric,
 historical_median_return numeric,
 sample_size integer,
 catalyst jsonb,
 model_version text not null default 'weekly-signal-v1',
 created_at timestamptz not null default now(),
 evaluated_at timestamptz,
 exit_date date,
 exit_price numeric,
 actual_return numeric,
 benchmark_return numeric,
 excess_return numeric,
 correct_direction boolean,
 unique(company_id,signal_date,horizon_days,model_version)
);
create index if not exists research_predictions_signal_date_idx on public.research_predictions(signal_date desc);
create index if not exists research_predictions_company_idx on public.research_predictions(company_id,signal_date desc);
alter table public.research_predictions enable row level security;
revoke all on table public.research_predictions from public, anon, authenticated;
grant select,insert,update,delete on table public.research_predictions to service_role;
